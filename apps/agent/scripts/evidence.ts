/**
 * Writes evidence/payments.md, evidence/guard-blocks.md and evidence/reppo.md
 * from the agent's database, for the README and judges.
 *
 *   pnpm evidence
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { errandMetrics, formatUsd, statsByVersion } from "@errand/core";
import { initStore, store } from "../src/store";

const dir = path.resolve(import.meta.dirname, "../../../evidence");
mkdirSync(dir, { recursive: true });

async function main() {
  await initStore();
  const list = (await store.list(500)).filter((e) => e.mode === "live");
  const pay = ["| Date | Errand | Seller endpoint | Amount | Transaction |", "|---|---|---|---|---|"];
  const blocks = ["| Date | Errand | Requested | Rule | Reason |", "|---|---|---|---|---|"];
  const reppo = ["| Errand | Guard version | Eval id | Status | Score | Decision | Waste rate |", "|---|---|---|---|---|---|---|"];
  for (const e of list) {
    for (const p of e.payments) {
      pay.push(`| ${p.at.slice(0, 16)} | [${e.id}](/r/${e.id}) | ${p.endpointId} | ${formatUsd(p.amountUsd)} | ${p.explorerUrl ? `[${p.txHash?.slice(0, 10)}…](${p.explorerUrl})` : "see Kite dashboard"} |`);
    }
    for (const d of e.decisions.filter((x) => x.decision === "block")) {
      blocks.push(`| ${d.at.slice(0, 16)} | ${e.id} | ${d.candidate.url.split("?")[0]} (${formatUsd(d.candidate.priceUsd)}) | ${d.rule} | ${d.reason.replace(/\|/g, "/")} |`);
    }
    if (e.evaluation?.evalId) {
      const m = errandMetrics(e);
      reppo.push(`| ${e.id} | ${e.guardVersion} | ${e.evaluation.evalId} | ${e.evaluation.status} | ${e.evaluation.score ?? "-"} | ${e.evaluation.decision ?? "-"} | ${(m.wasteRate * 100).toFixed(0)}% |`);
    }
  }
  const versions = statsByVersion(list)
    .map((v) => `- **${v.guardVersion}**: ${v.errands} errands, ${v.graded} graded, avg Reppo score ${v.avgReppoScore?.toFixed(1) ?? "-"}, accept rate ${v.acceptRate !== null ? `${Math.round(v.acceptRate * 100)}%` : "-"}, avg waste ${(v.avgWasteRate * 100).toFixed(0)}%, cost per accepted answer ${v.costPerAcceptedUsd !== null ? formatUsd(v.costPerAcceptedUsd) : "-"}`)
    .join("\n");

  writeFileSync(path.join(dir, "payments.md"), `# Real payments\n\nGenerated by \`pnpm evidence\` from live errands only.\n\n${pay.join("\n")}\n`);
  writeFileSync(path.join(dir, "guard-blocks.md"), `# Blocked payments\n\n${blocks.join("\n")}\n`);
  writeFileSync(path.join(dir, "reppo.md"), `# Reppo evaluations\n\n## By guard version\n\n${versions || "_None yet._"}\n\n## Every evaluation\n\n${reppo.join("\n")}\n\nSample size is small; read the numbers as a direction, not proof.\n`);
  console.log(`Wrote evidence for ${list.length} live errands.`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
